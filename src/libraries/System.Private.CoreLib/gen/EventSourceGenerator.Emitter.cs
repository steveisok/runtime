        /// <summary>Code for a [GeneratedCode] attribute to put on the top-level generated members.</summary>
        private static readonly string s_generatedCodeAttribute = $"[global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"{typeof(EventSourceGenerator).Assembly.GetName().Name}\", \"{typeof(EventSourceGenerator).Assembly.GetName().Version}\")]";

        private static void EmitSourceFile(SourceProductionContext context, EventSourceClass ec)
        {
            if (ec.Diagnostic != null)
            {
                context.ReportDiagnostic(ec.Diagnostic);
                return;
            }

            StringBuilder sb = new StringBuilder(1024);

            sb.AppendLine(@"// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            sb.AppendLine();
            sb.AppendLine("using System;");
            sb.AppendLine("using System.Diagnostics.Tracing;");
            GenType(ec, sb);

            context.AddSource($"{ec.ClassName}.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        }

        private static void GenType(EventSourceClass ec, StringBuilder sb)
        {
            if (!string.IsNullOrWhiteSpace(ec.Namespace))
            {
                sb.AppendLine($@"
namespace {ec.Namespace}
{{");
            }

            sb.AppendLine($@"
    {s_generatedCodeAttribute}
    partial class {ec.ClassName}
    {{");

            if (ec.Events.Length > 0)
            {
                GenerateEventHandleFields(ec.Events, sb);
            }

            GenerateConstructor(ec, sb);

            if (ec.HasProviderMetadataProperty)
            {
                GenerateProviderMetadata(ec.SourceName, sb);
            }

            foreach (var evt in ec.Events)
            {
                GenerateEventMethod(evt, sb);
            }

            sb.AppendLine($@"
    }}");

            if (!string.IsNullOrWhiteSpace(ec.Namespace))
            {
                sb.AppendLine($@"
}}");
            }
        }

        private static void GenerateEventHandleFields(ImmutableArray<EventMethod> events, StringBuilder sb)
        {
            foreach (var evt in events)
            {
                sb.AppendLine($"        private nint _eventHandle{evt.EventId};");
            }
            sb.AppendLine();
        }

        private static void GenerateConstructor(EventSourceClass ec, StringBuilder sb)
        {
            sb.AppendLine($@"
        private {ec.ClassName}() : base(""{ec.SourceName}"", new Guid({ec.Guid.ToString("x").Replace("{", "").Replace("}", "")}))
        {{");

            foreach (var evt in ec.Events)
            {
                GenerateDefineEventCall(evt, sb);
            }

            sb.AppendLine("        }");
        }

        private static void GenerateDefineEventCall(EventMethod evt, StringBuilder sb)
        {
            string message = evt.Message is not null
                ? $"\"{EscapeString(evt.Message)}\""
                : "null";

            sb.AppendLine($"            _eventHandle{evt.EventId} = DefineEvent(");
            sb.AppendLine($"                {evt.EventId},");
            sb.AppendLine($"                \"{evt.MethodName}\",");
            sb.AppendLine($"                (EventLevel){evt.Level},");
            sb.AppendLine($"                (EventKeywords){evt.Keywords}L,");
            sb.AppendLine($"                (EventOpcode){evt.Opcode},");
            sb.AppendLine($"                (EventTask){evt.Task},");
            sb.AppendLine($"                (EventTags)0,");
            sb.AppendLine($"                {message});");
            sb.AppendLine();
        }

        private static void GenerateEventMethod(EventMethod evt, StringBuilder sb)
        {
            var parameters = BuildParameterList(evt.Parameters);

            sb.AppendLine($@"
        {evt.Accessibility} partial void {evt.MethodName}({parameters})
        {{
            if (!IsEnabled((EventLevel){evt.Level}, (EventKeywords){evt.Keywords}L))
                return;
");

            foreach (var param in evt.Parameters)
            {
                if (IsStringType(param.FullyQualifiedType))
                {
                    sb.AppendLine($"            {param.Name} ??= \"\";");
                }
            }

            int paramCount = evt.Parameters.Length;

            if (paramCount == 0)
            {
                sb.AppendLine("            unsafe");
                sb.AppendLine("            {");
                sb.AppendLine($"                WriteEventDirect({evt.EventId}, _eventHandle{evt.EventId}, null, null, 0, null);");
                sb.AppendLine("            }");
                sb.AppendLine("        }");
                return;
            }

            sb.AppendLine("            unsafe");
            sb.AppendLine("            {");

            var stringParams = new List<EventParameter>();
            foreach (var param in evt.Parameters)
            {
                if (IsStringType(param.FullyQualifiedType))
                {
                    stringParams.Add(param);
                }
            }

            foreach (var param in stringParams)
            {
                sb.AppendLine($"                fixed (char* __ptr_{param.Name} = {param.Name})");
            }

            if (stringParams.Count > 0)
            {
                sb.AppendLine("                {");
            }

            string indent = stringParams.Count > 0 ? "                    " : "                ";
            sb.AppendLine($"{indent}EventData* __data = stackalloc EventData[{paramCount}];");
            sb.AppendLine();

            for (int i = 0; i < evt.Parameters.Length; i++)
            {
                EmitParameterDataAssignment(evt.Parameters[i], i, sb, indent);
            }

            sb.AppendLine($"{indent}WriteEventDirect({evt.EventId}, _eventHandle{evt.EventId}, null, null, {paramCount}, __data);");

            if (stringParams.Count > 0)
            {
                sb.AppendLine("                }");
            }
            sb.AppendLine("            }");
            sb.AppendLine("        }");
        }

        private static void EmitParameterDataAssignment(EventParameter param, int index, StringBuilder sb, string indent)
        {
            string type = param.FullyQualifiedType;

            if (IsStringType(type))
            {
                sb.AppendLine($"{indent}__data[{index}].DataPointer = (nint)__ptr_{param.Name};");
                sb.AppendLine($"{indent}__data[{index}].Size = ({param.Name}.Length + 1) * sizeof(char);");
            }
            else if (IsPrimitiveNumericType(type))
            {
                string sizeOfType = GetSizeOfExpression(type);
                sb.AppendLine($"{indent}{{");
                sb.AppendLine($"{indent}    var __temp_{param.Name} = {param.Name};");
                sb.AppendLine($"{indent}    __data[{index}].DataPointer = (nint)(&__temp_{param.Name});");
                sb.AppendLine($"{indent}    __data[{index}].Size = {sizeOfType};");
                sb.AppendLine($"{indent}}}");
            }
            else if (type == "global::System.Guid" || type == "System.Guid")
            {
                sb.AppendLine($"{indent}{{");
                sb.AppendLine($"{indent}    var __temp_{param.Name} = {param.Name};");
                sb.AppendLine($"{indent}    __data[{index}].DataPointer = (nint)(&__temp_{param.Name});");
                sb.AppendLine($"{indent}    __data[{index}].Size = sizeof(Guid);");
                sb.AppendLine($"{indent}}}");
            }
            else if (type == "bool" || type == "global::System.Boolean" || type == "System.Boolean")
            {
                sb.AppendLine($"{indent}{{");
                sb.AppendLine($"{indent}    int __temp_{param.Name} = {param.Name} ? 1 : 0;");
                sb.AppendLine($"{indent}    __data[{index}].DataPointer = (nint)(&__temp_{param.Name});");
                sb.AppendLine($"{indent}    __data[{index}].Size = sizeof(int);");
                sb.AppendLine($"{indent}}}");
            }
            else
            {
                sb.AppendLine($"{indent}// Unsupported type: {type} - using ToString()");
                sb.AppendLine($"{indent}{{");
                sb.AppendLine($"{indent}    string __str_{param.Name} = {param.Name}?.ToString() ?? \"\";");
                sb.AppendLine($"{indent}    fixed (char* __strptr_{param.Name} = __str_{param.Name})");
                sb.AppendLine($"{indent}    {{");
                sb.AppendLine($"{indent}        __data[{index}].DataPointer = (nint)__strptr_{param.Name};");
                sb.AppendLine($"{indent}        __data[{index}].Size = (__str_{param.Name}.Length + 1) * sizeof(char);");
                sb.AppendLine($"{indent}    }}");
                sb.AppendLine($"{indent}}}");
            }
        }

        private static string BuildParameterList(ImmutableArray<EventParameter> parameters)
        {
            var sb = new StringBuilder();
            for (int i = 0; i < parameters.Length; i++)
            {
                if (i > 0)
                {
                    sb.Append(", ");
                }
                var param = parameters[i];
                sb.Append($"{param.FullyQualifiedType}{(param.IsNullable ? "?" : "")} {param.Name}");
            }
            return sb.ToString();
        }

        private static bool IsStringType(string type)
        {
            return type is "string" or "global::System.String" or "System.String" or "string?";
        }

        private static bool IsPrimitiveNumericType(string type)
        {
            return type is
                "int" or "global::System.Int32" or "System.Int32" or
                "long" or "global::System.Int64" or "System.Int64" or
                "short" or "global::System.Int16" or "System.Int16" or
                "byte" or "global::System.Byte" or "System.Byte" or
                "sbyte" or "global::System.SByte" or "System.SByte" or
                "uint" or "global::System.UInt32" or "System.UInt32" or
                "ulong" or "global::System.UInt64" or "System.UInt64" or
                "ushort" or "global::System.UInt16" or "System.UInt16" or
                "float" or "global::System.Single" or "System.Single" or
                "double" or "global::System.Double" or "System.Double" or
                "nint" or "global::System.IntPtr" or "System.IntPtr" or
                "nuint" or "global::System.UIntPtr" or "System.UIntPtr";
        }

        private static string GetSizeOfExpression(string type)
        {
            return type switch
            {
                "int" or "global::System.Int32" or "System.Int32" => "sizeof(int)",
                "long" or "global::System.Int64" or "System.Int64" => "sizeof(long)",
                "short" or "global::System.Int16" or "System.Int16" => "sizeof(short)",
                "byte" or "global::System.Byte" or "System.Byte" => "sizeof(byte)",
                "sbyte" or "global::System.SByte" or "System.SByte" => "sizeof(sbyte)",
                "uint" or "global::System.UInt32" or "System.UInt32" => "sizeof(uint)",
                "ulong" or "global::System.UInt64" or "System.UInt64" => "sizeof(ulong)",
                "ushort" or "global::System.UInt16" or "System.UInt16" => "sizeof(ushort)",
                "float" or "global::System.Single" or "System.Single" => "sizeof(float)",
                "double" or "global::System.Double" or "System.Double" => "sizeof(double)",
                "nint" or "global::System.IntPtr" or "System.IntPtr" => "sizeof(nint)",
                "nuint" or "global::System.UIntPtr" or "System.UIntPtr" => "sizeof(nuint)",
                _ => $"sizeof({type})"
            };
        }

        private static string EscapeString(string value)
        {
            return value
                .Replace("\\", "\\\\")
                .Replace("\"", "\\\"")
                .Replace("\n", "\\n")
                .Replace("\r", "\\r")
                .Replace("\t", "\\t");
        }

        private static void GenerateProviderMetadata(string sourceName, StringBuilder sb)
        {
            sb.Append(@"
        private protected override ReadOnlySpan<byte> ProviderMetadata => [");

            byte[] metadataBytes = MetadataForString(sourceName);
            foreach (byte b in metadataBytes)
            {
                sb.Append($"0x{b:x}, ");
            }

            sb.AppendLine(@"];");
        }

        // From System.Private.CoreLib
        private static byte[] MetadataForString(string name)
        {
            CheckName(name);
            int metadataSize = Encoding.UTF8.GetByteCount(name) + 3;
            byte[]? metadata = new byte[metadataSize];
            ushort totalSize = checked((ushort)(metadataSize));
            metadata[0] = unchecked((byte)totalSize);
            metadata[1] = unchecked((byte)(totalSize >> 8));
            Encoding.UTF8.GetBytes(name, 0, name.Length, metadata, 2);
            return metadata;
        }

        private static void CheckName(string? name)
        {
            if (name != null && 0 <= name.IndexOf('\0'))
            {
                throw new ArgumentOutOfRangeException(nameof(name));
            }
        }
